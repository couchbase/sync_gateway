//go:build !windows

package main

import (
	"os/exec"
	"syscall"
	"time"
)

// killProcessTreeOnCancel makes cancellation kill cmd's whole process group, because killing gotestsum
// alone leaves go test and the test binary running and holding the output pipe open.
func killProcessTreeOnCancel(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error {
		return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL)
	}
	cmd.WaitDelay = 30 * time.Second
}
